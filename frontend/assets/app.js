async function runPipeline() {
  if (!state.profile) {
    showToast('Please complete your profile first.', 'error');
    navigate('profile');
    return;
  }

  const btn = $('btn-generate');
  btn.disabled = true;
  btn.innerHTML = `<div class="spinner" style="width:18px;height:18px;border-width:2px;"></div> Running Pipeline...`;

  showEl('pipeline-progress');
  hideEl('generate-error');
  resetPipelineUI();
  updateAgentDots('idle');

  /* Simulate agent progress since the backend runs all 4 sequentially */
  const steps = [
    { id: 'ps-profiler',   dot: 'dot-profiler',   label: 'Profiling your skills...', delay: 0 },
    { id: 'ps-curriculum', dot: 'dot-curriculum',  label: 'Designing curriculum...', delay: 0 },
    { id: 'ps-resource',   dot: 'dot-resource',    label: 'Curating resources...',  delay: 0 },
    { id: 'ps-assessment', dot: 'dot-assessment',  label: 'Building assessment...', delay: 0 },
  ];

  setStepStatus('ps-profiler', 'active', 'Profiling your skills & gaps...');
  setDot('dot-profiler', 'active');

  /* We fire the real API call simultaneously */
  let apiPromise;
  try {
    apiPromise = fetch(`${API_BASE}/generate`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(state.profile),
    });
  } catch (err) {
    handleGenerateError(err.message);
    resetGenBtn(btn);
    return;
  }

  /* Cycle through step animations while waiting */
  const tickInterval = setInterval(() => {
    // Update status text every 10 seconds to cycle through steps visually
    const activeStep = document.querySelector('.pipeline-step.active');
    if (!activeStep) return;
    const statusEl = activeStep.querySelector('.pipeline-status');
    if (statusEl) {
      const dots = statusEl.textContent.endsWith('...') ? '' : '...';
      statusEl.textContent = statusEl.textContent.replace(/\.+$/, '') + '..';
    }
  }, 800);

  /* Move to next step animation every 25s (total ~100s budget) */
  const stepTimings = [0, 25000, 55000, 85000];
  stepTimings.forEach((t, i) => {
    if (i === 0) return; // profiler already started
    setTimeout(() => {
      setStepStatus(steps[i-1].id, 'done', 'Complete ✓');
      setDot(steps[i-1].dot, 'done');
      setStepStatus(steps[i].id, 'active', steps[i].label);
      setDot(steps[i].dot, 'active');
    }, t);
  });

  try {
    const res = await apiPromise;
    clearInterval(tickInterval);

    if (!res.ok) {
      const errData = await res.json().catch(() => ({ detail: 'Unknown error' }));
      handleGenerateError(errData.detail || `HTTP ${res.status}`);
      resetGenBtn(btn);
      return;
    }

    const data = await res.json();
    state.result = data;
    localStorage.setItem('pathforge_result', JSON.stringify(data));

    /* Mark all done */
    steps.forEach(s => { setStepStatus(s.id, 'done', 'Complete ✓'); setDot(s.dot, 'done'); });
    updateAgentDots('done');

    renderAllOutputs();

    showToast('Learning path generated! Explore your results.', 'success', 6000);

    /* Auto-navigate to gap report */
    setTimeout(() => navigate('gap-report'), 1200);

  } catch (err) {
    clearInterval(tickInterval);
    handleGenerateError(err.message || 'Network error — is the API running?');
    resetGenBtn(btn);
    return;
  }

  resetGenBtn(btn);
}

function handleGenerateError(msg) {
  $('generate-error-text').textContent = `Error: ${msg}`;
  showEl('generate-error');
  showToast(`Generation failed: ${msg}`, 'error', 8000);
  updateAgentDots('idle');
}

function resetGenBtn(btn) {
  btn.disabled = false;
  btn.innerHTML = `<svg width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><polygon points="13 2 3 14 12 14 11 22 21 10 12 10 13 2"/></svg> Launch AI Pipeline`;
}

function setStepStatus(id, status, label) {
  const el = $(id);
  if (!el) return;
  el.className = `pipeline-step ${status}`;
  el.querySelector('.pipeline-status').textContent = label;
}

function setDot(id, status) {
  const el = $(id);
  if (!el) return;
  el.className = `agent-dot ${status}`;
}

function resetPipelineUI() {
  ['ps-profiler','ps-curriculum','ps-resource','ps-assessment'].forEach(id => {
    setStepStatus(id, '', 'Waiting...');
  });
  ['dot-profiler','dot-curriculum','dot-resource','dot-assessment'].forEach(id => {
    setDot(id, '');
  });
}

function updateAgentDots(status) {
  const ids = ['dot-profiler','dot-curriculum','dot-resource','dot-assessment'];
  if (status === 'done')  ids.forEach(id => setDot(id, 'done'));
  else if (status === 'idle') ids.forEach(id => setDot(id, ''));
}

