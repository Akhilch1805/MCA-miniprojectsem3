function renderQuiz(assessmentMd) {
  if (!assessmentMd) return;

  const quizEl = $('quiz-content');
  quizEl.innerHTML = `<div class="markdown-body">${renderMarkdown(assessmentMd)}</div>`;
  showBlock('quiz-submit-card');

  // Update description
  const moduleNum = state.profile?.generate_quiz_for_module || 1;
  $('quiz-card-desc').textContent = `Module ${moduleNum} Assessment — 7 questions including MCQ, short-answer, and code-completion.`;
}

async function submitQuiz() {
  if (!state.result) {
    showToast('Please generate a learning path first.', 'error');
    return;
  }

  /* Collect answers from any textarea / radio in quiz content */
  const answers = {};
  const radios    = $('quiz-content').querySelectorAll('input[type="radio"]:checked');
  const textareas = $('quiz-content').querySelectorAll('textarea');

  radios.forEach((r, i)    => { answers[`q${i+1}`] = r.value || r.labels?.[0]?.textContent || r.nextSibling?.textContent?.trim() || 'selected'; });
  textareas.forEach((t, i) => { answers[`q${radios.length + i + 1}`] = t.value; });

  /* If no structured inputs found, use placeholder answers */
  if (Object.keys(answers).length === 0) {
    for (let i = 1; i <= 7; i++) answers[`q${i}`] = 'Learner answer pending';
  }

  const btn = $('btn-submit-quiz');
  btn.disabled = true;
  btn.innerHTML = `<div class="spinner" style="width:16px;height:16px;border-width:2px;"></div> Evaluating...`;

  try {
    const res = await fetch(`${API_BASE}/assess`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        module_number:   state.profile?.generate_quiz_for_module || 1,
        enriched_roadmap: state.result?.enriched_roadmap || '',
        answers,
      }),
    });

    if (!res.ok) {
      const errData = await res.json().catch(() => ({ detail: 'Unknown error' }));
      throw new Error(errData.detail || `HTTP ${res.status}`);
    }

    const data = await res.json();
    showAssessmentResults(data.assessment_report);
    showToast('Assessment submitted! Check your adaptation report below.', 'success');

    /* Update progress */
    const progress = JSON.parse(localStorage.getItem('pathforge_progress') || '{}');
    progress[`module_${state.profile?.generate_quiz_for_module}`] = { submitted: true, timestamp: Date.now() };
    localStorage.setItem('pathforge_progress', JSON.stringify(progress));

  } catch (err) {
    showToast(`Submission failed: ${err.message}`, 'error');
  } finally {
    btn.disabled = false;
    btn.innerHTML = `<svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><path d="M22 11.08V12a10 10 0 11-5.93-9.14"/><polyline points="22 4 12 14.01 9 11.01"/></svg> Submit Answers`;
  }
}

