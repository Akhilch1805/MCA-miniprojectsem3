function navigate(page) {
  state.page = page;

  /* Update sidebar items */
  document.querySelectorAll('.sidebar-item').forEach(b => {
    b.classList.toggle('active', b.dataset.page === page);
  });

  /* Show/hide page views */
  document.querySelectorAll('.page-view').forEach(v => v.style.display = 'none');
  const pageEl = $(`page-${page}`);
  if (pageEl) pageEl.style.display = '';

  /* Update topbar */
  const meta = PAGE_META[page] || {};
  $('topbar-title').textContent    = meta.title    || page;
  $('topbar-subtitle').textContent = meta.subtitle || '';

  /* Show/hide export button */
  const exportPages = ['gap-report','roadmap','resources','assessment'];
  $('btn-export').style.display = exportPages.includes(page) ? 'inline-flex' : 'none';

  /* Enrich generate page with profile data */
  if (page === 'generate') renderGeneratePage();

  /* Render progress page */
  if (page === 'progress') renderProgressPage();

  /* Close mobile sidebar */
  $('sidebar').classList.remove('open');
}

