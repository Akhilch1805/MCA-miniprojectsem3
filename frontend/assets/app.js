/* ═══════════════════════════════════════════
   PROGRESS PAGE
   ═══════════════════════════════════════════ */
function renderProgressPage() {
  const container = $('progress-content');
  const profile = state.profile;
  const result  = state.result;
  const progress = JSON.parse(localStorage.getItem('pathforge_progress') || '{}');

  if (!profile || !result) return; // keep empty state

  /* Extract module count from roadmap */
  const roadmapText = result.roadmap || '';
  const moduleMatches = roadmapText.match(/## Module \d+/g) || [];
  const moduleCount = Math.max(moduleMatches.length, 4);

  let html = `
    <div class="mb-24">
      <div class="text-xs text-dim mb-8">LEARNING PATH FOR</div>
      <div class="fw-700 text-teal" style="font-size:1.2rem;">${profile.target_role}</div>
    </div>
    <div class="mb-24">
  `;

  let completedModules = 0;
  for (let i = 1; i <= moduleCount; i++) {
    const done = !!progress[`module_${i}`];
    if (done) completedModules++;
    const pct = done ? 100 : (i === completedModules + 1 && result) ? 20 : 0;

    html += `
      <div class="progress-bar-wrap mb-16">
        <div class="progress-bar-label">
          <span>Module ${i}</span>
          <span class="${done ? 'text-green' : 'text-muted'}">${done ? '✓ Complete' : i <= completedModules + 1 ? 'In Progress' : 'Upcoming'}</span>
        </div>
        <div class="progress-bar">
          <div class="progress-bar-fill" style="width:${pct}%"></div>
        </div>
      </div>
    `;
  }

  const overallPct = Math.round((completedModules / moduleCount) * 100);
  html += `
    </div>
    <hr class="divider" />
    <div class="mb-16">
      <div class="progress-bar-label">
        <span class="fw-600">Overall Progress</span>
        <span class="text-teal fw-700">${overallPct}%</span>
      </div>
      <div class="progress-bar" style="height:10px;">
        <div class="progress-bar-fill" style="width:${overallPct}%"></div>
      </div>
    </div>
    <div class="flex gap-12 flex-wrap mt-16">
      <div class="card-glass" style="padding:16px 24px; flex:1; text-align:center; min-width:100px;">
        <div style="font-size:1.8rem; font-weight:800; color:var(--c-teal);">${completedModules}</div>
        <div class="text-xs text-muted">Modules Done</div>
      </div>
      <div class="card-glass" style="padding:16px 24px; flex:1; text-align:center; min-width:100px;">
        <div style="font-size:1.8rem; font-weight:800; color:var(--c-purple);">${moduleCount}</div>
        <div class="text-xs text-muted">Total Modules</div>
      </div>
      <div class="card-glass" style="padding:16px 24px; flex:1; text-align:center; min-width:100px;">
        <div style="font-size:1.8rem; font-weight:800; color:var(--c-green);">${profile.weekly_hours}</div>
        <div class="text-xs text-muted">Hrs/Week</div>
      </div>
    </div>
  `;

  container.innerHTML = html;
}

/* ═══════════════════════════════════════════
   EXPORT
   ═══════════════════════════════════════════ */
function exportCurrentPage() {
  const page = state.page;
  const map = {
    'gap-report': ['gap_report',     `pathforge_gap_report`],
    'roadmap':    ['roadmap',         `pathforge_roadmap`],
    'resources':  ['enriched_roadmap',`pathforge_resources`],
    'assessment': ['assessment',      `pathforge_assessment`],
  };

  if (!map[page] || !state.result) {
    showToast('Nothing to export yet.', 'info');
    return;
  }

  const [key, filename] = map[page];
  const content = state.result[key] || '';

  const blob = new Blob([content], { type: 'text/markdown;charset=utf-8' });
  const url  = URL.createObjectURL(blob);
  const a    = document.createElement('a');
  a.href     = url;
  a.download = `${filename}_${Date.now()}.md`;
  a.click();
  URL.revokeObjectURL(url);

  showToast('Markdown file downloaded!', 'success');
}

