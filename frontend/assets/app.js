let skills = [];

function initProfilePage() {
  const hoursInput   = $('input-hours');
  const hoursVal     = $('hours-val');
  const rangeDisplay = $('range-display');

  hoursInput.addEventListener('input', () => {
    const v = hoursInput.value;
    const pct = ((v - 1) / (60 - 1)) * 100;
    hoursInput.style.setProperty('--pct', pct + '%');
    hoursVal.textContent    = `${v} hrs`;
    rangeDisplay.textContent = `${v} hrs`;
  });
  hoursInput.dispatchEvent(new Event('input')); // init

  /* Skill tag input */
  const skillsInput = $('input-skills');
  skillsInput.addEventListener('keydown', e => {
    if (e.key === 'Enter' || e.key === ',') {
      e.preventDefault();
      addSkill(skillsInput.value.trim().replace(/,$/, ''));
      skillsInput.value = '';
    }
  });
  skillsInput.addEventListener('blur', () => {
    if (skillsInput.value.trim()) {
      addSkill(skillsInput.value.trim());
      skillsInput.value = '';
    }
  });

  /* Profile form submit */
  $('profile-form').addEventListener('submit', e => {
    e.preventDefault();
    saveProfile();
  });

  /* Go to generate button */
  $('btn-go-generate').addEventListener('click', () => navigate('generate'));
}

function addSkill(skill) {
  if (!skill || skills.includes(skill)) return;
  skills.push(skill);
  renderSkillTags();
}

function removeSkill(skill) {
  skills = skills.filter(s => s !== skill);
  renderSkillTags();
}

function renderSkillTags() {
  const container = $('skills-tags');
  container.innerHTML = '';
  skills.forEach(s => {
    const tag = document.createElement('div');
    tag.className = 'skill-tag';
    tag.innerHTML = `${s}<button class="skill-tag-remove" aria-label="Remove ${s}">×</button>`;
    tag.querySelector('.skill-tag-remove').addEventListener('click', () => removeSkill(s));
    container.appendChild(tag);
  });
}

function saveProfile() {
  const name = $('input-name').value.trim();
  const role = $('input-target-role').value.trim();

  if (!name || !role) {
    showToast('Please fill in your name and target role.', 'error');
    return;
  }
  if (skills.length === 0) {
    showToast('Please add at least one current skill.', 'error');
    return;
  }

  state.profile = {
    name,
    current_skills: [...skills],
    experience_years: parseInt($('input-exp').value),
    target_role: role,
    weekly_hours: parseInt($('input-hours').value),
    generate_quiz_for_module: parseInt($('input-module').value),
  };

  localStorage.setItem('pathforge_profile', JSON.stringify(state.profile));

  /* Show preview */
  renderProfilePreview();
  showBlock('profile-preview');
  showEl('btn-go-generate');
  showToast('Profile saved! You can now generate your learning path.', 'success');
  updateAgentDots('idle');
}

